"""Cut the painted world map (Canva) into the layered format map.js expects: wm-base + one feathered piece per land.
   Region shapes come from tools/segment_map.py (a label image that follows the painting's own coastlines, ridges and colour changes).
   usage: python3 tools/make_worldmap.py map.png labels.png"""
import sys, json, io
import numpy as np, cv2
from PIL import Image, ImageFilter, ImageEnhance
SRC, LAB = sys.argv[1], sys.argv[2]; S = 1.5
NAMES = {'L1': 'The Hollow Fields', 'L2': 'The Salt Wastes', 'L3': 'The Deep Quarry', 'L4': 'The Hollowdeep Mines', 'L5': "Cogwright's Ruin", 'L6': 'The Sheer Stair', 'L7': 'The Waystone Hills', 'L8': 'The Crossroads'}
LABEL_AT = {'L1': (1330, 580), 'L2': (1110, 600), 'L3': (950, 400), 'L4': (800, 640), 'L5': (580, 430), 'L6': (480, 620), 'L7': (200, 520), 'L8': (260, 330)}
im = Image.open(SRC).convert('RGB'); W, H = round(im.width * S), round(im.height * S); im = im.resize((W, H), Image.LANCZOS)
labels = cv2.resize(cv2.imread(LAB, cv2.IMREAD_GRAYSCALE), (W, H), interpolation=cv2.INTER_NEAREST)
def save(img, name, q=82):
    b = io.BytesIO(); img.save(b, 'WEBP', quality=q, alpha_quality=85, method=6); open(f'src/art/{name}.webp', 'wb').write(b.getvalue()); return len(b.getvalue()) // 1024
print('base', save(ImageEnhance.Brightness(im).enhance(0.92), 'wm-base'), 'KB')
defs = {'w': W, 'h': H, 'order': list(NAMES), 'regions': []}
for i, rid in enumerate(NAMES, 1):
    m = ((labels == i) * 255).astype(np.uint8)
    cs, _ = cv2.findContours(m, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE); c = max(cs, key=cv2.contourArea)
    poly = cv2.approxPolyDP(c, 2.5, True)[:, 0, :]
    x0, y0, w, h = cv2.boundingRect(c); x0, y0 = max(0, x0 - 8), max(0, y0 - 8); x1, y1 = min(W, x0 + w + 16), min(H, y0 + h + 16)
    a = Image.fromarray(m).filter(ImageFilter.GaussianBlur(2.2))      # a soft edge, so the lifted piece does not look cut with scissors
    piece = im.copy(); piece.putalpha(a); piece = piece.crop((x0, y0, x1, y1))
    kb = save(piece, 'wm-' + rid.lower())
    path = 'M' + 'L'.join(f'{int(x)} {int(y)}' for x, y in poly) + 'Z'
    lx, ly = LABEL_AT[rid]
    defs['regions'].append({'id': rid, 'name': NAMES[rid], 'x': x0, 'y': y0, 'w': x1 - x0, 'h': y1 - y0, 'lx': round(lx * S), 'ly': round(ly * S), 'path': path})
    print(rid, NAMES[rid], kb, 'KB', len(poly), 'pts')
open('src/worldmap_defs.js', 'w').write('/* generated by tools/make_worldmap.py: layered world map geometry (regions from tools/segment_map.py) */\nvar WM_DEFS = ' + json.dumps(defs, separators=(',', ':')) + ';\n')
