"""Cut a single painted world map (Canva) into the layered format map.js expects: wm-base + one feathered piece per land.
   usage: python3 tools/make_worldmap.py map.png    (region polygons below, in the painting's own pixels)"""
import sys, json, io
from PIL import Image, ImageDraw, ImageFilter, ImageEnhance
SRC = sys.argv[1]; S = 1.5   # upscale 1536x1024 -> 2304x1536
REG = [  # id, name, polygon, label point
  ('L1', 'The Hollow Fields', [(1210, 330), (1490, 300), (1500, 600), (1450, 830), (1260, 830), (1200, 700), (1220, 560)], (1360, 560)),
  ('L2', 'The Salt Wastes', [(1040, 380), (1210, 330), (1220, 560), (1200, 700), (1180, 840), (1000, 860), (960, 720), (990, 560)], (1110, 600)),
  ('L3', 'The Deep Quarry', [(850, 250), (1060, 200), (1100, 330), (1040, 380), (990, 520), (900, 520), (850, 420)], (960, 380)),
  ('L4', 'The Hollowdeep Mines', [(660, 260), (780, 190), (850, 250), (850, 420), (900, 520), (990, 560), (960, 720), (1000, 860), (830, 880), (700, 800), (600, 700), (620, 560), (680, 520)], (770, 600)),
  ('L5', "Cogwright's Ruin", [(490, 330), (570, 260), (660, 260), (680, 520), (620, 560), (530, 540), (480, 460)], (575, 410)),
  ('L6', 'The Sheer Stair', [(300, 420), (480, 440), (530, 540), (620, 560), (600, 700), (560, 800), (320, 800), (290, 640)], (420, 620)),
  ('L7', 'The Waystone Hills', [(40, 400), (300, 420), (290, 640), (200, 640), (60, 600)], (160, 520)),
  ('L8', 'The Crossroads', [(40, 230), (140, 190), (300, 200), (440, 260), (490, 330), (480, 440), (300, 420), (40, 400)], (230, 320)),
]
im = Image.open(SRC).convert('RGB'); W, H = round(im.width * S), round(im.height * S); im = im.resize((W, H), Image.LANCZOS)
def save(img, name, q=82):
    b = io.BytesIO(); img.save(b, 'WEBP', quality=q, alpha_quality=80, method=6); open(f'src/art/{name}.webp', 'wb').write(b.getvalue()); return len(b.getvalue()) // 1024
print('base', save(ImageEnhance.Brightness(im).enhance(0.92), 'wm-base'), 'KB')
defs = {'w': W, 'h': H, 'order': [r[0] for r in REG], 'regions': []}
for rid, name, poly, lab in REG:
    P = [(x * S, y * S) for x, y in poly]; xs = [p[0] for p in P]; ys = [p[1] for p in P]
    x0, y0, x1, y1 = int(min(xs)) - 6, int(min(ys)) - 6, int(max(xs)) + 6, int(max(ys)) + 6
    m = Image.new('L', (W, H), 0); ImageDraw.Draw(m).polygon(P, fill=255); m = m.filter(ImageFilter.GaussianBlur(5))
    piece = im.copy(); piece.putalpha(m); piece = piece.crop((x0, y0, x1, y1))
    kb = save(piece, 'wm-' + rid.lower())
    path = 'M' + 'L'.join(f'{round(x)} {round(y)}' for x, y in P) + 'Z'
    defs['regions'].append({'id': rid, 'name': name, 'x': x0, 'y': y0, 'w': x1 - x0, 'h': y1 - y0, 'lx': round(lab[0] * S), 'ly': round(lab[1] * S), 'path': path})
    print(rid, name, kb, 'KB')
open('src/worldmap_defs.js', 'w').write('/* generated by tools/make_worldmap.py: layered world map geometry */\nvar WM_DEFS = ' + json.dumps(defs, separators=(',', ':')) + ';\n')
